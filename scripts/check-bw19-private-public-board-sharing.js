#!/usr/bin/env node
'use strict';
const fs = require('fs');
const assert = require('assert');
const read = (file) => fs.readFileSync(file, 'utf8');
const storage = read('api/_boards-storage.js');
const access = read('api/_board-access.js');
const token = read('api/_board-public-sharing.js');
const item = read('api/boards/[id].js');
const sharing = read('api/boards/[id]/sharing.js');
const list = read('api/boards/index.js');
const browser = read('app.js');
const presence = read('api/boards/presence/[id].js');
for (const column of ['public_view_enabled BOOLEAN NOT NULL DEFAULT FALSE', 'public_view_token_hash TEXT', 'public_view_token_created_at TIMESTAMPTZ']) assert(storage.includes(column));
assert.doesNotMatch(storage, /UPDATE boards SET public_view|randomBytes/);
assert.match(token, /randomBytes\(PUBLIC_TOKEN_BYTES\)/);
assert.match(token, /PUBLIC_TOKEN_BYTES = 32/);
assert.match(token, /\^\[A-Za-z0-9_\-\]\{43\}\$/);
assert.match(token, /createHash\('sha256'\)/);
assert.match(token, /timingSafeEqual/);
assert.match(token, /catch \{/);
assert.doesNotMatch(list, /public_view_token|public_view_enabled/);
assert.match(sharing, /access\?\.role !== 'owner'/);
assert.match(sharing, /Object\.keys\(body\)\.length !== 1/);
assert.match(sharing, /public_view_token_hash = \$2/);
assert.match(sharing, /public_view_token_hash = NULL, public_view_token_created_at = NULL/);
assert.match(sharing, /public_view_token \}/);
assert.doesNotMatch(sharing, /console\./);
assert.match(item, /x-board-public-token/);
assert.match(item, /role: 'public_viewer'/);
assert.match(item, /return res\.status\(404\)/);
assert.match(item, /public_view_enabled/);
assert.match(access, /\['non_owner', 'anonymous'\]/);
assert.match(access, /isUnowned && user\?\.email/);
const restricted = read('api/_board-serializer.js').split('if (restricted) {')[1].split('\n  }')[0];
for (const secret of ['brand_id', 'brand_core_snapshot', 'owner_id', 'owner_email', 'public_view']) assert(!restricted.includes(secret));
assert.match(browser, /\^#public=\(\[A-Za-z0-9_\-\]\{43\}\)\$/);
assert.match(browser, /"X-Board-Public-Token": token/);
assert.doesNotMatch(presence, /X-Board-Public-Token|publicBoardToken/);
assert.doesNotMatch(browser.match(/function serializeState\([^]*?\n\}/)?.[0] || '', /publicBoardToken|boardSharing/);
assert.match(browser, /Public view · Read-only Canvas/);
assert.match(browser, /This Board is private or the public link is no longer valid/);
for (const label of ['Copy Board Link', 'Create Public View Link', 'Replace Public View Link', 'Disable Public View']) assert(browser.includes(label));
assert.match(browser, /window\.confirm\("Replace public view link/);
assert.match(browser, /window\.confirm\("Disable public view/);
assert.match(browser, /generation !== state\.boardSharing\.generation/);
assert.match(browser, /status: "reload-required"/);
assert.match(browser, /data\?\.access\?\.role !== "public_viewer"/);
assert.match(item + sharing + list, /Cache-Control', 'private, no-store/);
console.log('BW-19 private Boards and revocable public view link checks passed.');
