'use strict';
const fs = require('fs');
const assert = require('assert');
const read = (p) => fs.readFileSync(p, 'utf8');
const storage = read('api/_boards-storage.js');
const access = read('api/_board-access.js');
const item = read('api/_board-serializer.js');
const list = read('api/boards/index.js');
const members = read('api/boards/[id]/editors/index.js');
const presence = read('api/boards/presence/[id].js');
const browser = read('app.js');
assert.match(storage, /role IN \('editor', 'viewer'\)/);
assert.match(storage, /board_editors_board_email_uidx/);
assert.match(storage, /email = LOWER\(email\)/);
assert.match(members, /role !== 'editor' && role !== 'viewer'/);
assert.match(members, /email === ownerEmail/);
assert.match(members, /ON CONFLICT \(board_id, email\)/);
for (const role of ['owner', 'editor', 'viewer', 'unowned', 'non_owner', 'anonymous_shared']) assert(access.includes(role));
for (const capability of ['canRead','canEdit','canViewBoardBrandCore','canManageMembers','canRename','canDelete','canChangeBrandAssociation','canRefreshFromCanonical','canRestoreBrandCore','canViewPresence']) assert(access.includes(capability));
assert.match(list, /THEN be\.role/);
assert.match(list, /row\.access_role === 'viewer'/);
assert.match(item, /brand_visibility: 'hidden'/);
const restrictedShape = item.split("if (restricted) {")[1].split("\n  }")[0];
for (const secret of ['brand_core_snapshot','brand_id','owner_email','owner_id']) assert(!restrictedShape.includes(secret));
assert.match(presence, /getBoardAccess\(boardId/);
assert.match(presence, /!access\?\.canViewPresence/);
assert.match(browser, /Cannot edit or access Board Brand Core/);
assert.match(browser, /Does not receive access to the Canonical Brand or other Boards/);
assert.match(browser, /clearAutosaveTimer\(\)/);
assert.match(browser, /brand_visibility !== "hidden"/);
console.log('BW-18 Board access role and sensitive-data boundary checks passed.');
