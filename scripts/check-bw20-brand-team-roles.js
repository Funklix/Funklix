#!/usr/bin/env node
'use strict';
const fs = require('fs');
const assert = require('assert');
const read = (path) => fs.readFileSync(path, 'utf8');
const storage = read('api/_brands-storage.js');
const access = read('api/_brand-access.js');
const members = read('api/brands/[id]/members.js');
const collection = read('api/brands/index.js');
const item = read('api/brands/[id].js');
const boardAccess = read('api/_board-access.js');
const boardList = read('api/boards/index.js');
const boardItem = read('api/boards/[id].js');
const serializer = read('api/_board-serializer.js');
const browser = read('app.js');

for (const field of ['brand_id UUID NOT NULL', 'email TEXT NOT NULL', 'role TEXT NOT NULL', 'name TEXT NULL', 'avatar TEXT NULL', 'invited_by TEXT NULL', 'created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()', 'updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()']) assert(storage.includes(field));
assert.match(storage, /REFERENCES brands\(id\) ON DELETE CASCADE/);
assert.match(storage, /UNIQUE \(brand_id, email\)/);
assert.match(storage, /email = LOWER\(email\)/);
assert.match(storage, /role IN \('admin', 'editor', 'viewer'\)/);
assert.match(storage, /CREATE TABLE IF NOT EXISTS brand_members/);
assert.doesNotMatch(storage, /DROP TABLE|INSERT INTO brand_members[^]*SELECT/);
for (const capability of ['canReadBrand', 'canViewCanonicalBrandCore', 'canEditCanonicalBrand', 'canCreateBrandBoards', 'canViewAllBrandBoards', 'canEditAllBrandBoards', 'canManageBrandMembers', 'canManageBrandAdmins']) assert(access.includes(capability));
assert.match(access, /CASE WHEN b\.owner_email = \$2 THEN 'owner' ELSE bm\.role/);
assert.match(members, /MEMBER_ROLES = new Set\(\['admin', 'editor', 'viewer'\]\)/);
assert.match(members, /targetEmail === normalizeEmail\(brand\.owner_email\)/);
assert.match(members, /!access\.canManageBrandAdmins/);
assert.match(members, /targetEmail === actorEmail/);
assert.match(members, /ON CONFLICT \(brand_id, email\) DO UPDATE/);
assert.doesNotMatch(members, /SELECT[^`]*brand_core|public_view_token/);
assert.match(collection, /LEFT JOIN brand_members/);
assert.match(collection, /brand_access_role/);
assert.match(collection, /ORDER BY CASE WHEN b\.owner_email/);
assert.doesNotMatch(collection.match(/if \(req\.method === 'GET'\)[^]*?return res\.status\(200\)/)?.[0] || '', /brand_core/);
assert.match(item, /access\.canEditCanonicalBrand/);
assert.match(item, /revision = revision \+ 1/);
for (const role of ['brand_owner', 'brand_admin', 'brand_editor', 'brand_viewer']) assert(boardAccess.includes(role));
assert.match(boardList, /LEFT JOIN brand_members bm/);
assert.match(boardList, /bm\.role = 'viewer'.*'brand_viewer'/s);
assert.match(boardItem, /brandAccess\.canEditCanonicalBrand/);
assert.match(serializer, /access\.role === 'viewer' \|\| access\.role === 'public_viewer'/);
for (const label of ['Brand Owner', 'Brand Admin', 'Brand Editor', 'Brand Viewer', 'Brand Team']) assert(browser.includes(label));
for (const wording of ['Can edit this Canonical Brand and all associated Boards. Can manage Brand Editors and Viewers.', 'Can edit this Canonical Brand and all associated Boards. Cannot manage Brand members.', 'Can view this Canonical Brand and all associated Boards. Cannot make changes.']) assert(browser.includes(wording));
assert.match(browser, /canManageBrandMembers/);
assert.match(browser, /canManageBrandAdmins/);
assert.match(browser, /form\.dataset\.pending/);
assert.match(browser, /canonicalBrandDetail\.requestId === generation/);
assert.match(browser, /\["owner", "admin", "editor"\]\.includes\(brand\.role\)/);
assert.match(browser, /clearAutosaveTimer\(\)/);
assert.match(boardItem, /x-board-public-token/);
console.log('BW-20 Canonical Brand team role checks passed.');
